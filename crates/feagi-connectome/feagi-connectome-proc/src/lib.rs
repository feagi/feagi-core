//region Cortical Type Family

use feagi_macro_components::model_family::cortical_type_family_template::CorticalTypeFamilyTemplate;

/// Defines and validates the template of a cortical type family: a base trait generic over a
/// member of a model family, and a struct per cortical type generic over the members of the
/// single model of the model family it uses. Cortical types may be grouped into super types, to
/// any depth. Generates the exported template macro `{family}_family_template!`, whose single
/// input is the path of a macro to call with the validated template. Pass it
/// [`expand_cortical_type_family`] to generate the family's types
///
/// # Example
///
/// ```ignore
/// define_cortical_type_family_template! {
///     /// Every cortical area type
///     Family: CorticalAreaType,
///     Error: CorticalAreaTypeSelectionError,
///     ModelFamily: NeuronModel,
///     ModelFamilyError: NeuronModelSelectionError,
///
///     Types: {
///         /// Cortical types unique within the genome
///         Foundation: {
///             Power: FoundationPower,
///         }
///         Interconnect: FeagiAdvanced,
///     }
/// }
///
/// cortical_area_type_family_template!(expand_cortical_type_family);
/// ```
#[proc_macro]
pub fn define_cortical_type_family_template(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    match syn::parse::<CorticalTypeFamilyTemplate>(input) {
        Err(e) => e.to_compile_error().into(),
        Ok(template) => template.generate_rust_template_macro().into(),
    }
}

/// Expands a cortical type family template, as given by its template macro. Generates:
/// - `{Family}Kind`, with a variant per cortical type and super type directly of the family, and
///   `{Path}SuperTypeKind` per super type, with a variant per cortical type and super type
///   directly of it. A super type variant holds its kind. All are data less, `Copy`, and
///   serializable, with `ALL` and `name`
/// - The error `{Error}`, of accessing data as a cortical type or super type it does not hold,
///   which wraps the model family error
/// - `{Family}Enum<C>` and `{Path}SuperTypeEnum<C>` per super type, generic over a container of
///   the model family, nested as the kinds are. A cortical type variant holds the
///   `{Model}QuantEnum<C>` of its model. Each is `Clone`, `Debug`, `PartialEq`, and serializable
///   whenever all the data it may hold is, and has `kind` and `{model_family}_kind`, with `From`
///   and `TryFrom` between each enum and those of its super types
/// - The trait `{Family}Member`, implemented for every cortical type struct at every member of
///   its model, holding its kind and converting its data between itself and `{Family}Enum<C>`,
///   through which `{Family}Enum<C>` has `from_data`, `try_as`, `try_as_mut`, and `try_into_data`
/// - The dispatch macro `with_{family}!`, which runs the same code against whichever cortical
///   type is held, optionally aliasing its struct and model member
///
/// Must be in scope where this is expanded: the module of the model family, as
/// [`expand_model_family`] expects, and the module named the snake case of the family, such as
/// `cortical_area_type`, with nested sub modules per super type and cortical type named their
/// snake case, the module of each cortical type holding its struct `{Family}{Path}<NM>`, such as
/// `cortical_area_type::foundation::power::CorticalAreaTypeFoundationPower<NM>`. The dispatch
/// macro also expects the generated items in the family module. The crate must depend on
/// `feagi_basis`, which serde is reached through
#[proc_macro]
pub fn expand_cortical_type_family(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    match syn::parse::<CorticalTypeFamilyTemplate>(input) {
        Err(e) => e.to_compile_error().into(),
        Ok(template) => template.generate_rust_family().into(),
    }
}

