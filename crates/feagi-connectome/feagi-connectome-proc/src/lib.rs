//region Cortical Dynamics Quantization

use feagi_macro_components::cortical_dynamics::cortical_dynamics_quantization::CorticalDynamicsQuantizationTemplate;

/// Defines and validates the quantization template of a cortical dynamics model. Generates the
/// template macro `cortical_dynamics_quantization_{model}_template!`, whose single input is the
/// path of a macro to call with the validated template. Pass it
/// [`expand_cortical_dynamics_quantization`] to generate the model's types
///
/// # Example
///
/// ```ignore
/// define_cortical_dynamics_quantization_template! {
///     /// Quantization for the Feagi Advanced model
///     FeagiAdvanced
///
///     // Required, the single NeuronLayoutTag of the model, shared by every quantization level
///     NeuronLayout: NeuronLayoutTagVoxel
///
///     // Required, every level's `NeuronModel::NeurogenesisDefaults<FIQ>`, written in terms of `FIQ`
///     // and `Self` (the level). Implements `NeurogenesisScratchVarianceGenerator<FIQ, Self>`
///     NeurogenesisDefaults: FeagiAdvancedNeurogenesisDefaults<FIQ, Self>
///
///     // Required, every level's `NeuronModel::NeurogenesisGenerator<FIQ>`, written in terms of
///     // `FIQ` and `Self` (the level). Implements `NeurogenesisByGenerator<FIQ, Self>`
///     NeurogenesisGenerator: FeagiAdvancedNeurogenesisGenerator<FIQ, Self>
///
///     // Optional, each one of QDECIMAL, QUINT or QSINT
///     Quantizables: {
///         /// How long till the neuron can fire again
///         RefractoryPeriod: QDECIMAL,
///     }
///
///     // Each sets MembranePotentialQuant and every quantizable
///     QuantizationLevels: {
///         Float32: {
///             MembranePotentialQuant: f32,
///             RefractoryPeriod: f32,
///         }
///     }
///
///     // Optional, as are each of its data types: CorticalDataProperties, CorticalDataInternal,
///     // CorticalDataScratch, CorticalDataVariance, NeuronDataInternal, NeuronDataScratch,
///     // NeuronDataVariance
///     DataSpecifications: {
///         CorticalDataProperties: {
///             /// Becomes `RefractoryPeriod<NM::RefractoryPeriod>`
///             refractory_period: RefractoryPeriod,
///             /// Kept as written
///             some_count: u32,
///         }
///     }
/// }
///
/// cortical_dynamics_quantization_feagi_advanced_template!(expand_cortical_dynamics_quantization);
/// ```
#[proc_macro]
pub fn define_cortical_dynamics_quantization_template(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    match syn::parse::<CorticalDynamicsQuantizationTemplate>(input) {
        Err(e) => e.to_compile_error().into(),
        Ok(template) => template.generate_rust_template_macro().into(),
    }
}

/// Expands a cortical dynamics quantization template, as given by its template macro. Generates:
/// - A wrapper struct per quantizable, through `feagi_basis`'s `create_wrapped_quantized_*!`
/// - The model's `NM{Model}Trait` trait, such as `NMFeagiAdvancedTrait`, a sub trait of
///   `NeuronModel` fixing its `NeuronLayoutTag` and each of its data types to the model's data
///   struct of that type, holding an associated type per quantizable
/// - One `NM{Model}Quant{Level}` unit marker struct per quantization level, such as
///   `NMFeagiAdvancedQuantDefaultQuant`, implementing `NeuronModel` (with the layout,
///   `NeurogenesisDefaults` and `NeurogenesisGenerator` of the template) and the model trait
/// - The tag `NM{Model}Tag`, naming the model as a whole. It is an alias of the first quantization
///   level, so its `NeuronModel::NeuronLayoutTag` is the layout of the model
/// - `CorticalDataVarianceSpecification` for `NM{Model}DataCorticalVariance`, if the model gives
///   fields for neither variance data type. Otherwise it must be implemented by hand
/// - A `NM{Model}Data{DataType}<NM>` struct for every data type, the data type dropping its
///   `Data`, such as `NMFeagiAdvancedDataCorticalProperties` for `CorticalDataProperties`, with its
///   fields public, a `PhantomData` of the
///   quantization, a const `new` constructor, a `requantize` to any other quantization level of
///   the model, and its specification trait implemented. `requantize` errors if a decimal becomes
///   infinite or NaN, clamps integers, and clones any other field. Data types not given hold only
///   the `PhantomData`, which is public so that a struct may be written out with its fields named.
///   `NM{Model}DataNeuronVariance` is not serializable
///
/// Enums over the quantization levels of a model are generated by its model family, see
/// [`expand_model_family`]
///
/// Must be in scope where this is expanded: `NeuronModel`, `NeuronLayoutOf`, `MembranePotentialQuantization`, the seven
/// data specification traits (such as `CorticalDataPropertiesSpecification`), `FeagiIndexQuantization`,
/// the `NeurogenesisDefaults` and `NeurogenesisGenerator` types, any types the data fields name,
/// and the layout type the `NeuronLayout` names.
/// The crate must depend on `serde` and `half`, which the wrapper structs use
#[proc_macro]
pub fn expand_cortical_dynamics_quantization(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    match syn::parse::<CorticalDynamicsQuantizationTemplate>(input) {
        Err(e) => e.to_compile_error().into(),
        Ok(template) => template.generate_rust_quantization().into(),
    }
}

