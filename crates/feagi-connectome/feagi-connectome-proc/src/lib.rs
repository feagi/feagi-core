//region Model Family

use feagi_macro_components::model_family::model_family_template::ModelFamilyTemplate;

/// Defines and validates the template of a model family: a base trait, a sub trait of it per
/// model, and a zero sized marker struct per quantization level of each model. Generates the
/// exported template macro `{family}_family_template!`, whose single input is the path of a macro
/// to call with the validated template. Pass it [`expand_model_family`] to generate the family's
/// types
///
/// # Example
///
/// ```ignore
/// define_model_family_template! {
///     /// Every neuron model
///     Family: NeuronModel,
///
///     Models: {
///         /// Always fires
///         ExclusivePower: {
///             Float16,
///             Float32,
///         }
///         FeagiAdvanced: { DefaultQuant }
///     }
/// }
///
/// neuron_model_family_template!(expand_model_family);
/// ```
#[proc_macro]
pub fn define_model_family_template(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    match syn::parse::<ModelFamilyTemplate>(input) {
        Err(e) => e.to_compile_error().into(),
        Ok(template) => template.generate_rust_template_macro().into(),
    }
}

/// Expands a model family template, as given by its template macro. Every generated name is fixed,
/// prefixed `NM`, as the family only ever holds the neuron models. Generates:
/// - `NM{Model}QuantKind` per model, a data less enum with a variant per quantization level, and
///   `NMKind`, with a variant per model holding its `NM{Model}QuantKind`. Both are `Copy`,
///   serializable, and name their variants
/// - `NM{Model}QuantEnum<C>` per model, with a variant per quantization level holding
///   `C::Of<marker>`, and `NMEnum<C>`, with a variant per model holding its
///   `NM{Model}QuantEnum<C>`, with `From` and `TryFrom` between them. Each is `Clone`, `Debug`,
///   `PartialEq`, and serializable whenever all the data it may hold is, and has `kind`,
///   `from_data`, `try_as`, `try_as_mut`, and `try_into_data`
/// - `NM{Model}Member` per model, converting data of a member between itself and
///   `NM{Model}QuantEnum<C>`, and the implementations of it and of `NMMember` for every marker struct
/// - The exported dispatch macros `with_nm!` and `with_nm_{model}!` per model, which run the same
///   code against whichever member is held, optionally aliasing its marker struct and model module.
///   Their paths start at `$crate::connectome_basis::neuron_model`, so they need no imports
///
/// Expanded in the module of the hand written items of the family, which has the base trait
/// `{Family}` in scope and defines `NMContainer` (`type Of<M: {Family}>`), `NMMember`, and
/// `NMAccessError`. That module must be re-exported as `crate::connectome_basis::neuron_model`,
/// next to a module per model named its snake case, such as `exclusive_power`, holding the model
/// trait `NM{Model}Trait`, the tag `NM{Model}Tag` (a type distinct per model implementing
/// `{Family}`), every marker struct `NM{Model}Quant{Level}` of it, as
/// `expand_cortical_dynamics_quantization` generates them, and `BurstEngineDynamics`. Marker
/// structs must be unit structs. The crate must depend on `serde`
#[proc_macro]
pub fn expand_model_family(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    match syn::parse::<ModelFamilyTemplate>(input) {
        Err(e) => e.to_compile_error().into(),
        Ok(template) => template.generate_rust_family().into(),
    }
}

