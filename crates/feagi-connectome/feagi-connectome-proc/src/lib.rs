//region Model Family

use feagi_macro_components::model_family::model_family_template::ModelFamilyTemplate;

/// Defines and validates the template of a model family: a base trait, a sub trait of it per
/// model, and a zero sized marker struct per quantization level of each model. Generates the
/// exported template macro `{family}_family_template!`, whose single input is the path of a macro
/// to call with the validated template. Pass it [`expand_model_family`] to generate the family's
/// types
///
/// # Example
///
/// ```ignore
/// define_model_family_template! {
///     /// Every neuron model
///     Family: NeuronModel,
///     Error: NeuronModelSelectionError,
///
///     Models: {
///         /// Always fires
///         FoundationPower: {
///             Float16,
///             Float32,
///         }
///         FeagiAdvanced: { DefaultQuant }
///     }
/// }
///
/// neuron_model_family_template!(expand_model_family);
/// ```
#[proc_macro]
pub fn define_model_family_template(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    match syn::parse::<ModelFamilyTemplate>(input) {
        Err(e) => e.to_compile_error().into(),
        Ok(template) => template.generate_rust_template_macro().into(),
    }
}

/// Expands a model family template, as given by its template macro. Generates:
/// - `{Model}QuantKind` per model, a data less enum with a variant per quantization level, and
///   `{Family}Kind`, with a variant per model holding its `{Model}QuantKind`. Both are `Copy`,
///   serializable, and name their variants
/// - The error `{Error}`, of accessing data as a member or model it does not hold
/// - The trait `{Family}Container`, a kind of data generic over the members of the family as
///   `type Of<M: {Family}>`, to be implemented on a zero sized struct per kind of data
/// - `{Model}QuantEnum<C>` per model, with a variant per quantization level holding
///   `C::Of<marker>`, and `{Family}Enum<C>`, with a variant per model holding its
///   `{Model}QuantEnum<C>`, with `From` and `TryFrom` between them. Each is `Clone`, `Debug`,
///   `PartialEq`, and serializable whenever all the data it may hold is, and has `kind`,
///   `from_data`, `try_as`, `try_as_mut`, `try_into_data`, and `try_as_marker`
/// - The trait `{Family}Member`, holding the kind and marker of a member and converting its data
///   between itself and `{Family}Enum<C>`, and `{Family}{Model}Member` per model, doing the same
///   with `{Model}QuantEnum<C>`. Both are implemented for every marker struct
/// - The dispatch macros `with_{family}!`, `with_{family}_{model}!` per model, and
///   `with_{family}_kind!`, which run the same code against whichever member is held, optionally
///   aliasing its marker struct
///
/// Must be in scope where this is expanded: the module named the snake case of the family, such
/// as `neuron_model`, holding the base trait `{Family}`, with a sub module per model named the
/// snake case of the model, such as `foundation_power`, holding the model trait `{Family}{Model}` and
/// every marker struct `{Family}{Model}{Level}` of it. Marker structs must be unit structs. The
/// dispatch macros also expect the generated items in the family module. The crate must depend on
/// `feagi_basis`, which serde is reached through
#[proc_macro]
pub fn expand_model_family(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    match syn::parse::<ModelFamilyTemplate>(input) {
        Err(e) => e.to_compile_error().into(),
        Ok(template) => template.generate_rust_family().into(),
    }
}

