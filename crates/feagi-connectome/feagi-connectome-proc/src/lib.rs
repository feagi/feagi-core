//region Cortical Type Family

use feagi_macro_components::model_family::cortical_type_family_template::CorticalTypeFamilyTemplate;

/// Defines and validates the template of a cortical type family: a base trait, and cortical types
/// each belonging to exactly one super type and allowing one or more models of a model family. The
/// number of a super type or cortical type is its key, unique among its siblings, from 1 to 255.
/// Generates the exported template macro `{family}_family_template!`, whose single input is the path
/// of a macro to call with the validated template. Pass it [`expand_cortical_type_family`] to
/// generate the family's types
///
/// # Example
///
/// ```ignore
/// define_cortical_type_family_template! {
///     /// Every cortical area type
///     Family: CorticalAreaType,
///     Error: CorticalAreaTypeSelectionError,
///     ModelFamily: NeuronModel,
///     Identifier: CorticalIdentifier,
///     IdentifierError: CorticalIdentifierParseError,
///
///     Types: {
///         /// Cortical types that keep the brain running
///         Exclusive = 1: {
///             Power = 1: [ExclusivePower],
///         }
///         Processing = 2: {
///             Interconnect = 1: [FeagiAdvanced, FeagiSimple],
///         }
///     }
/// }
///
/// cortical_area_type_family_template!(expand_cortical_type_family);
/// ```
#[proc_macro]
pub fn define_cortical_type_family_template(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    match syn::parse::<CorticalTypeFamilyTemplate>(input) {
        Err(e) => e.to_compile_error().into(),
        Ok(template) => template.generate_rust_template_macro().into(),
    }
}

/// Expands a cortical type family template, as given by its template macro. Generates:
/// - The module named the snake case of the family, such as `cortical_area_type`, re-exporting
///   everything public where this is expanded
/// - `{Family}Kind`, with a variant per super type holding its `{SuperType}SuperTypeKind`, which has
///   a variant per cortical type. All are data less, `Copy`, and serializable, with `name` and `key`
/// - The error `{Error}`, of accessing data as a cortical type or super type it does not hold,
///   which wraps `NMAccessError`
/// - `{Family}Enum<C>`, `{SuperType}SuperTypeEnum<C>` per super type, and
///   `{SuperType}{Type}ModelEnum<C>` per cortical type, generic over a container of the model family
///   and nested as the kinds are. A model enum holds the `NM{Model}QuantEnum<C>` of each model the
///   cortical type allows. Each is `Clone`, `Debug`, `PartialEq`, and serializable whenever all the
///   data it may hold is, and has `{model_family}_kind`, with `From` and `TryFrom` between each enum
///   and the one above it
/// - The trait `Uses{Model}` per allowed model, to be implemented by hand by each cortical type
///   allowing it. Giving a cortical type a layout other than its model's is a compile error, as is
///   a cortical type listing a model without implementing this. Its `new_defaults_generator` gives
///   the `NeurogenesisDefaultsGenerator` of a new area of the cortical type laid out as given,
///   holding the defaults of the cortical type for that model, which a client may edit before the
///   area is created
/// - The trait `{Family}Member`, implemented for every cortical type, holding its kind and its model
///   enum as `type Models<C>`, and
///   `{Family}MemberAt<M>`, implemented for every cortical type at every member of the models it
///   allows, converting its data between itself and `{Family}Enum<C>`, through which
///   `{Family}Enum<C>` has `from_data`, `try_as`, `try_as_mut`, and `try_into_data`
/// - The dispatch macro `with_{family}!`, which runs the same code against whichever cortical
///   type is held, optionally aliasing its struct and model member
///
/// Must be public where this is expanded: the base trait `{Family}`, with associated type
/// `NeuronLayout`, and a module per super type named its snake case, holding a unit struct per
/// cortical type named as in the template, such as `exclusive::Power`. Must be in scope where this
/// is expanded: the module of the model family, `NeurogenesisDefaultsGenerator`,
/// `FeagiIndexQuantization`, and `NeuronLayoutOf`. The
/// crate must depend on `serde`
#[proc_macro]
pub fn expand_cortical_type_family(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    match syn::parse::<CorticalTypeFamilyTemplate>(input) {
        Err(e) => e.to_compile_error().into(),
        Ok(template) => template.generate_rust_family().into(),
    }
}

/// Expands the identifier of a cortical type family, as given by its template macro, which is exactly
/// 8 bytes: the super type key, the cortical type key, and 6 bytes of inner ID. Generates:
/// - `{Identifier}`, which only ever holds valid bytes, with `new`, `from_path`, `try_from_bytes`,
///   `to_bytes`, `path`, `kind`, and `inner_bytes`. It is `Copy`, hashable, and serialized as its 8
///   bytes in any format, and `Option<{Identifier}>` is 8 bytes as well
/// - `{Identifier}Path`, with a variant per super type holding its `{SuperType}{Identifier}Path`,
///   which has a variant per cortical type holding its inner ID. These are what an identifier is
///   matched as, and are never stored
/// - The error `{IdentifierError}`, naming the first layer that rejected the bytes given
///
/// [`expand_cortical_type_family`] must also be expanded in the same place, as this uses its kinds
/// and `{Family}Member`. The base trait `{Family}` must have the associated type `Inner`, which must
/// convert to and from `[u8; 6]`, returning the exact same bytes. The crate must depend on `serde`
#[proc_macro]
pub fn expand_cortical_identifier(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    match syn::parse::<CorticalTypeFamilyTemplate>(input) {
        Err(e) => e.to_compile_error().into(),
        Ok(template) => template.generate_rust_identifier().into(),
    }
}

/// Expands the map of cortical areas of a cortical type family, as given by its template macro,
/// which holds areas by super type, then cortical type, then inner ID. What is held for each cortical
/// type may differ, and can never disagree with the identifier it is found by. Generates:
/// - `{Family}MapValue`, deciding what is held per cortical type as `type Of<T: {Family}Member>`, to
///   be implemented on a zero sized struct per kind of map
/// - `{Family}Map<V>`, with a public `{SuperType}SuperTypeMap<V>` field per super type, which has a
///   public `HashMap` field per cortical type from its inner ID to what is held. It has `get`,
///   `get_mut`, `contains`, `of`, `of_mut`, `identifiers`, `len`, and `is_empty`
/// - `{Family}Ref<'a, V>` and `{Family}RefMut<'a, V>`, which `get` and `get_mut` return, with a variant
///   per super type holding its `{SuperType}SuperTypeRef<'a, V>` or `{SuperType}SuperTypeRefMut<'a, V>`,
///   which have a variant per cortical type
/// - `{Family}MapMember`, implemented for every cortical type, through which `of` and `of_mut` give
///   the `HashMap` of a cortical type known at compile time
///
/// [`expand_cortical_type_family`] and [`expand_cortical_identifier`] must also be expanded in the
/// same place, as this uses their items. Must be used with `std`
#[proc_macro]
pub fn expand_cortical_area_map(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    match syn::parse::<CorticalTypeFamilyTemplate>(input) {
        Err(e) => e.to_compile_error().into(),
        Ok(template) => template.generate_rust_area_map().into(),
    }
}

