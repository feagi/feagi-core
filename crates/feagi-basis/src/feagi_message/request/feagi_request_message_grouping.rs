use crate::feagi_message::request::feagi_request_descriptor::FeagiRequestMessageDescriptor;
use crate::feagi_message::request::feagi_request_message_category::{FeagiCategoryRequester, FeagiRequestCategory};
use crate::parallelism::feagi_channel::request_response_channel::channel_backend::FeagiRequestResponseChannelBackend;

//region Category

/// Nests the message descriptors of a category, as `NMDes<Head, NMDes<..., NNull>>`
pub struct NMDes<Head, Tail>
where
    Head: FeagiRequestMessageDescriptor,
    // Tail can be either another NMDes or a NNull (tail)
    {
    pub head: Head,
    pub tail: Tail
}

/// Tail of the `NMDes` and `NCat`
pub struct NNull;

//endregion

//region Category Group

/// A group of categories, passed around as one so a worker can serve or make requests of all
/// of them. Purely a grouping, each category is independent with its own channel and request /
/// response enums. All categories share the same channel backend
///
/// Implemented by the requesters struct of groups generated by `define_request_category_group`
pub trait FeagiRequestCategoryGroup<Channels>
where
    Channels: FeagiRequestResponseChannelBackend,
{
    /// The configurables of every category of the group
    type Configurables;

    /// Every category of the group, with its requester and configurables, nested as
    /// `NCat<FeagiConfiguredCategoryRequester<A, Channels>, NCat<..., NNull>>`. Walked by generic
    /// code serving the group (such as REST routing)
    type NestedCategories;

    /// Consume self to pair each category's requester with its configurables
    fn into_nested_categories(self, configurables: Self::Configurables) -> Self::NestedCategories;
}

/// Nests per category items of a group, as `NCat<Head, NCat<..., NNull>>`
pub struct NCat<Head, Tail>
    // Tail can be either another NCat or a NNull (tail)
    {
    pub head: Head,
    pub tail: Tail
}

/// A category's requester, with the configurables its message paths are built from
pub struct FeagiConfiguredCategoryRequester<Category, Channels>
where
    Category: FeagiRequestCategory,
    Channels: FeagiRequestResponseChannelBackend,
{
    pub requester: FeagiCategoryRequester<Category, Channels>,
    pub configurables: &'static Category::Configurables,
}

/// A group with no categories
impl<Channels> FeagiRequestCategoryGroup<Channels> for NNull
where
    Channels: FeagiRequestResponseChannelBackend,
{
    type Configurables = ();
    type NestedCategories = NNull;

    fn into_nested_categories(self, _configurables: Self::Configurables) -> Self::NestedCategories {
        NNull
    }
}

//endregion
