use crate::feagi_message::request::feagi_request_descriptor::FeagiRequestMessageDescriptor;
use crate::feagi_message::request::feagi_request_message_category::{FeagiCategoryRequester, FeagiRequestCategory};
use crate::parallelism::feagi_channel::request_response_channel::FeagiRequestResponseChannelBackend;

//region Category

/// Nests the message descriptors of a category, as `NMDes<Head, NMDes<..., NNull>>`
pub struct NMDes<Head, Tail>
where
    Head: FeagiRequestMessageDescriptor,
    // Tail can be either another NMDes or a NNull (tail)
{
    pub head: Head,
    pub tail: Tail,
}

/// Tail of the `NMDes` and `NCat`
pub struct NNull;

//endregion

//region Category Group

/// A group of categories, passed around as one so a worker can serve or make requests of all
/// of them. Purely a grouping, each category is independent with its own channel and request /
/// response enums. All categories share the same channel backend
///
/// Implemented by the requesters struct of groups generated by `define_request_category_group`,
/// by a lone `FeagiCategoryRequester` (a group of one), and by tuples of groups. Categories
/// served by different workers are joined with a tuple, such as
/// `(GenomeManagerRequesters<Channels>, FeagiCategoryRequester<SystemRequestCategory, Channels>)`,
/// whose configurables are the tuple of each member's configurables
pub trait FeagiRequestCategoryGroup<Channels>
where
    Channels: FeagiRequestResponseChannelBackend,
{
    /// The configurables of every category of the group
    type Configurables;

    /// Every category of the group, with its requester and configurables, nested as
    /// `NCat<FeagiConfiguredCategoryRequester<A, Channels>, NCat<..., NNull>>`. Walked by generic
    /// code serving the group (such as REST routing)
    type NestedCategories: FeagiNestedCategories;

    /// Consume self to pair each category's requester with its configurables
    fn into_nested_categories(self, configurables: Self::Configurables) -> Self::NestedCategories;
}

/// Nests per category items of a group, as `NCat<Head, NCat<..., NNull>>`
pub struct NCat<Head, Tail>
// Tail can be either another NCat or a NNull (tail)
{
    pub head: Head,
    pub tail: Tail,
}

/// A `NCat` chain (or `NNull`), which another chain can be appended to. Lets groups be joined
/// into one flat chain, so code walking a group never sees how it was put together
pub trait FeagiNestedCategories {
    /// This chain with `Other` in place of its `NNull`
    type Append<Other: FeagiNestedCategories>: FeagiNestedCategories;

    fn append<Other: FeagiNestedCategories>(self, other: Other) -> Self::Append<Other>;
}

impl FeagiNestedCategories for NNull {
    type Append<Other: FeagiNestedCategories> = Other;

    fn append<Other: FeagiNestedCategories>(self, other: Other) -> Self::Append<Other> {
        other
    }
}

impl<Head, Tail: FeagiNestedCategories> FeagiNestedCategories for NCat<Head, Tail> {
    type Append<Other: FeagiNestedCategories> = NCat<Head, Tail::Append<Other>>;

    fn append<Other: FeagiNestedCategories>(self, other: Other) -> Self::Append<Other> {
        NCat {
            head: self.head,
            tail: self.tail.append(other),
        }
    }
}

/// A category's requester, with the configurables its message paths are built from
pub struct FeagiConfiguredCategoryRequester<Category, Channels>
where
    Category: FeagiRequestCategory,
    Channels: FeagiRequestResponseChannelBackend,
{
    pub requester: FeagiCategoryRequester<Category, Channels>,
    pub configurables: &'static Category::Configurables,
}

/// A group with no categories
impl<Channels> FeagiRequestCategoryGroup<Channels> for NNull
where
    Channels: FeagiRequestResponseChannelBackend,
{
    type Configurables = ();
    type NestedCategories = NNull;

    fn into_nested_categories(self, _configurables: Self::Configurables) -> Self::NestedCategories {
        NNull
    }
}

/// A lone category, for one served apart from any generated group. Its configurables are the
/// category's own
impl<Category, Channels> FeagiRequestCategoryGroup<Channels> for FeagiCategoryRequester<Category, Channels>
where
    Category: FeagiRequestCategory,
    Channels: FeagiRequestResponseChannelBackend,
{
    type Configurables = &'static Category::Configurables;
    type NestedCategories = NCat<FeagiConfiguredCategoryRequester<Category, Channels>, NNull>;

    fn into_nested_categories(self, configurables: Self::Configurables) -> Self::NestedCategories {
        NCat {
            head: FeagiConfiguredCategoryRequester {
                requester: self,
                configurables,
            },
            tail: NNull,
        }
    }
}

/// The nested categories of the groups `$group`, in order, appended into one chain
macro_rules! joined_nested_categories {
    ($channels:ident; $last:ident) => {
        <$last as FeagiRequestCategoryGroup<$channels>>::NestedCategories
    };
    ($channels:ident; $head:ident, $($rest:ident),+) => {
        <<$head as FeagiRequestCategoryGroup<$channels>>::NestedCategories as FeagiNestedCategories>::Append<joined_nested_categories!($channels; $($rest),+)>
    };
}

/// Tuples of groups are one group, serving every category of each member in order. Members
/// are usually served by different workers
macro_rules! impl_group_for_tuple {
    ($($group:ident: $requesters:ident, $configurables:ident),+) => {
        impl<Channels, $($group),+> FeagiRequestCategoryGroup<Channels> for ($($group,)+)
        where
            Channels: FeagiRequestResponseChannelBackend,
            $( $group: FeagiRequestCategoryGroup<Channels>, )+
        {
            type Configurables = ($($group::Configurables,)+);
            type NestedCategories = joined_nested_categories!(Channels; $($group),+);

            fn into_nested_categories(self, configurables: Self::Configurables) -> Self::NestedCategories {
                let ($($requesters,)+) = self;
                let ($($configurables,)+) = configurables;
                impl_group_for_tuple!(@append $($requesters.into_nested_categories($configurables)),+)
            }
        }
    };
    (@append $last:expr) => { $last };
    (@append $head:expr, $($rest:expr),+) => {
        $head.append(impl_group_for_tuple!(@append $($rest),+))
    };
}

impl_group_for_tuple!(A: a_requesters, a_configurables);
impl_group_for_tuple!(A: a_requesters, a_configurables, B: b_requesters, b_configurables);
impl_group_for_tuple!(A: a_requesters, a_configurables, B: b_requesters, b_configurables, C: c_requesters, c_configurables);
impl_group_for_tuple!(A: a_requesters, a_configurables, B: b_requesters, b_configurables, C: c_requesters, c_configurables, D: d_requesters, d_configurables);
impl_group_for_tuple!(A: a_requesters, a_configurables, B: b_requesters, b_configurables, C: c_requesters, c_configurables, D: d_requesters, d_configurables, E: e_requesters, e_configurables);
impl_group_for_tuple!(A: a_requesters, a_configurables, B: b_requesters, b_configurables, C: c_requesters, c_configurables, D: d_requesters, d_configurables, E: e_requesters, e_configurables, F: f_requesters, f_configurables);
