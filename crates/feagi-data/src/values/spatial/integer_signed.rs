/// Stores [`SignedIntegerSpatial`] as an enum to erase the generic type and to make transport easier.
///
/// NOTE that due to how enums work in Rust, memory allocation will always be at i64 quant levels!
#[derive(Debug, Clone, Copy, Hash, PartialEq, Eq, ::serde::Serialize, ::serde::Deserialize)]
pub enum SignedIntegerSpatialEnum<const NUM_DIMS: usize> {
    I8(SignedIntegerSpatial<i8, NUM_DIMS>),
    I16(SignedIntegerSpatial<i16, NUM_DIMS>),
    I32(SignedIntegerSpatial<i32, NUM_DIMS>),
    I64(SignedIntegerSpatial<i64, NUM_DIMS>),
}

impl<const NUM_DIMS: usize> SignedIntegerSpatialEnum<NUM_DIMS> {
    /// Get what level of quantization is contained
    pub fn get_level(&self) -> SignedIntegerQuantizationLevel {
        match self {
            Self::I8(_) => SignedIntegerQuantizationLevel::I8,
            Self::I16(_) => SignedIntegerQuantizationLevel::I16,
            Self::I32(_) => SignedIntegerQuantizationLevel::I32,
            Self::I64(_) => SignedIntegerQuantizationLevel::I64,
        }
    }

    /// Tries to convert to a spatial value of another quantization, returning an error if any axis
    /// value does not fit.
    pub fn try_into_quant<Quant: QuantizedSignedIntegerTrait>(
        self,
    ) -> Result<SignedIntegerSpatial<Quant, NUM_DIMS>, FeagiDataValuesSpatialError> {
        match self {
            Self::I8(value) => value.try_to_quantization(),
            Self::I16(value) => value.try_to_quantization(),
            Self::I32(value) => value.try_to_quantization(),
            Self::I64(value) => value.try_to_quantization(),
        }
    }

    /// Converts to a spatial value of another quantization without checking if valid.
    pub fn into_quant<Quant: QuantizedSignedIntegerTrait>(self) -> SignedIntegerSpatial<Quant, NUM_DIMS> {
        match self {
            Self::I8(value) => value.to_quantization_unchecked(),
            Self::I16(value) => value.to_quantization_unchecked(),
            Self::I32(value) => value.to_quantization_unchecked(),
            Self::I64(value) => value.to_quantization_unchecked(),
        }
    }

    /// Converts to a spatial value of another quantization, clamping each axis value to fit.
    pub fn into_quantization_clamped<Quant: QuantizedSignedIntegerTrait>(self) -> SignedIntegerSpatial<Quant, NUM_DIMS> {
        match self {
            Self::I8(value) => value.to_quantization_clamped(),
            Self::I16(value) => value.to_quantization_clamped(),
            Self::I32(value) => value.to_quantization_clamped(),
            Self::I64(value) => value.to_quantization_clamped(),
        }
    }
}

