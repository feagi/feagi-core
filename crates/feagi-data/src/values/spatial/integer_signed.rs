use crate::values::quantizable::{
    QuantizedSignedIntegerTrait, QuantizedSignedIntegerUnwrappedTrait, SignedIntegerQuantizationLevel,
};
use crate::values::spatial::feagi_data_values_spatial_error::FeagiDataValuesSpatialError;

#[derive(Debug, Clone, Copy, Hash, PartialEq, Eq)]
pub struct SignedIntegerSpatial<Q: QuantizedSignedIntegerTrait, const NUM_DIMS: usize> {
    data: [Q; NUM_DIMS],
}

impl<Q: QuantizedSignedIntegerTrait, const NUM_DIMS: usize> serde::Serialize for SignedIntegerSpatial<Q, NUM_DIMS> {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: serde::Serializer,
    {
        self.data.as_slice().serialize(serializer)
    }
}

impl<'de, Q: QuantizedSignedIntegerTrait, const NUM_DIMS: usize> serde::Deserialize<'de> for SignedIntegerSpatial<Q, NUM_DIMS>
where
    Q: serde::Deserialize<'de>,
{
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        let values = Vec::<Q>::deserialize(deserializer)?;
        if values.len() != NUM_DIMS {
            return Err(serde::de::Error::custom(format!(
                "expected {} spatial elements, got {}",
                NUM_DIMS,
                values.len()
            )));
        }
        let data: [Q; NUM_DIMS] = values
            .try_into()
            .map_err(|_| serde::de::Error::custom("failed converting spatial elements to fixed-size array"))?;
        Ok(Self { data })
    }
}

/// Shared signed-integer spatial semantics for both raw and wrapped values.
pub trait SignedIntegerSpatialTrait<Q: QuantizedSignedIntegerTrait, const NUM_DIMS: usize>:
    Copy
    + Clone
    + Send
    + Sync
    + core::fmt::Debug
    + core::cmp::PartialEq
    + core::cmp::Eq
    + core::hash::Hash
    + Sized
    + 'static
{
    /// Number of spatial axes represented by this value.
    const NUM_DIMS: usize = NUM_DIMS;

    /// What quantization level this represents.
    const LEVEL: SignedIntegerQuantizationLevel = Q::LEVEL;

    /// Spatial of all elements as one.
    const QUANT_ONES: Self;

    /// Get a flat slice view of axis values.
    fn as_slice(&self) -> &[Q];

    /// Create from a correctly sized array.
    fn new_from_array(array: [Q; NUM_DIMS]) -> Self;

    /// Create from a correctly sized array of some other quant. Does NOT validate bounds.
    fn new_from_quant_unchecked<FromQuant: QuantizedSignedIntegerTrait>(
        value: SignedIntegerSpatial<FromQuant, NUM_DIMS>,
    ) -> Self;

    /// Create from a correctly sized array of some other quant, returning an error if any axis
    /// value does not fit in the current quantization.
    fn new_from_quant<FromQuant: QuantizedSignedIntegerTrait>(
        value: SignedIntegerSpatial<FromQuant, NUM_DIMS>,
    ) -> Result<Self, FeagiDataValuesSpatialError>;

    /// Create from a correctly sized array of some other quant, clamping each axis value to fit.
    fn new_from_quant_clamped<FromQuant: QuantizedSignedIntegerTrait>(
        value: SignedIntegerSpatial<FromQuant, NUM_DIMS>,
    ) -> Self;

    /// Clamps each axis value for another quantization, but does not change the quantization
    /// itself.
    fn clamp_for_quantization<ClampFor: QuantizedSignedIntegerTrait>(self) -> Self;

    /// Clamps each axis value for a runtime-provided quantization level, but does not change the
    /// quantization itself.
    fn clamp_for_quantization_level_runtime(self, level: SignedIntegerQuantizationLevel) -> Self;
}

/// Marker trait for raw [`SignedIntegerSpatial`] values.
pub trait SignedIntegerSpatialUnwrappedTrait<Q: QuantizedSignedIntegerTrait, const NUM_DIMS: usize>:
    SignedIntegerSpatialTrait<Q, NUM_DIMS>
{
}

/// Shared behaviour implemented by every strongly-typed wrapper generated by
/// [`create_wrapped_signed_integer_spatial`].
pub trait SignedIntegerSpatialWrappedTrait<Q: QuantizedSignedIntegerTrait, const NUM_DIMS: usize>:
    SignedIntegerSpatialTrait<Q, NUM_DIMS>
    + From<SignedIntegerSpatial<Q, NUM_DIMS>>
    + AsRef<SignedIntegerSpatial<Q, NUM_DIMS>>
{
    /// The underlying unwrapped spatial value this wrapper stores.
    type Spatial: SignedIntegerSpatialUnwrappedTrait<Q, NUM_DIMS>;

    /// Spatial of all elements as zero.
    const QUANT_ZEROS: Self;

    /// Create from an unwrapped spatial without checking any validity.
    fn wrap_unchecked(value: SignedIntegerSpatial<Q, NUM_DIMS>) -> Self;

    /// Removes the wrapper.
    fn dewrap(self) -> SignedIntegerSpatial<Q, NUM_DIMS>;

    /// Wrap an unwrapped spatial.
    fn wrap(value: SignedIntegerSpatial<Q, NUM_DIMS>) -> Self {
        Self::wrap_unchecked(value)
    }
}

impl<Q: QuantizedSignedIntegerTrait, const NUM_DIMS: usize> SignedIntegerSpatial<Q, NUM_DIMS> {
    /// What quantization level this represents
    pub const LEVEL: SignedIntegerQuantizationLevel = Q::LEVEL;

    /// Spatial of all elements as zero
    pub const QUANT_ZEROS: SignedIntegerSpatial<Q, NUM_DIMS> = Self::new_from_array_const([Q::QUANT_ZERO; NUM_DIMS]);

    /// Spatial of all elements as one
    pub const QUANT_ONES: SignedIntegerSpatial<Q, NUM_DIMS> = Self::new_from_array_const([Q::QUANT_ONE; NUM_DIMS]);

    /// Create self from a correctly sized array in const context
    pub const fn new_from_array_const(array: [Q; NUM_DIMS]) -> Self {
        Self { data: array }
    }

    /// Create self from a correctly sized array
    pub fn new_from_array(array: [Q; NUM_DIMS]) -> Self {
        Self { data: array }
    }

    /// Create self from a correctly sized isize array. Does NOT validate quantization bounds!
    pub fn new_from_isize_array_unchecked(isize_array: [isize; NUM_DIMS]) -> Self {
        let mut data = [Q::QUANT_ZERO; NUM_DIMS];
        data.iter_mut()
            .zip(isize_array.iter())
            .for_each(|(q, i)| *q = Q::quant_from_isize_unchecked(*i));
        Self { data }
    }

    /// Create self from a correctly sized isize array, returning an error if any axis value does
    /// not fit in the current quantization.
    pub fn new_from_isize_array(isize_array: [isize; NUM_DIMS]) -> Result<Self, FeagiDataValuesSpatialError> {
        let mut data = [Q::QUANT_ZERO; NUM_DIMS];
        for (q, &i) in data.iter_mut().zip(isize_array.iter()) {
            *q = Q::quant_try_from_isize(i).map_err(|e| e.into())?;
        }
        Ok(Self { data })
    }

    /// Create self from a correctly sized array of some other quant. Does NOT validate bounds!
    pub fn new_from_quant_unchecked<FromQuant: QuantizedSignedIntegerTrait>(value_array: SignedIntegerSpatial<FromQuant, NUM_DIMS>) -> Self {
        let mut data = [Q::QUANT_ZERO; NUM_DIMS];
        data.iter_mut()
            .zip(value_array.as_data_slice().iter())
            .for_each(|(q, &v)| *q = Q::from_quantization_unchecked(v));
        Self { data }
    }

    /// Create self from a correctly sized array of some other quant, returning an error if any
    /// axis value does not fit in the current quantization.
    pub fn new_from_quant<FromQuant: QuantizedSignedIntegerTrait>(
        value_array: SignedIntegerSpatial<FromQuant, NUM_DIMS>,
    ) -> Result<Self, FeagiDataValuesSpatialError> {
        let mut data = [Q::QUANT_ZERO; NUM_DIMS];
        for (q, &v) in data.iter_mut().zip(value_array.as_data_slice().iter()) {
            *q = Q::try_from_quantization(v).map_err(|e| e.into())?;
        }
        Ok(Self { data })
    }

    /// Create self from a correctly sized array of some other quant, clamping each axis value to
    /// fit in the current quantization.
    pub fn new_from_quant_clamped<FromQuant: QuantizedSignedIntegerTrait>(value_array: SignedIntegerSpatial<FromQuant, NUM_DIMS>) -> Self {
        let mut data = [Q::QUANT_ZERO; NUM_DIMS];
        data.iter_mut()
            .zip(value_array.as_data_slice().iter())
            .for_each(|(q, &v)| *q = Q::from_quantization_clamped(v));
        Self { data }
    }

    /// Converts this value from its current quantization to another quantization without checking if valid.
    pub fn to_quantization_unchecked<ToQuant: QuantizedSignedIntegerTrait>(self) -> SignedIntegerSpatial<ToQuant, NUM_DIMS> {
        let mut out = [ToQuant::QUANT_ZERO; NUM_DIMS];
        out.iter_mut()
            .zip(self.data.iter())
            .for_each(|(o, &s)| *o = ToQuant::from_quantization_unchecked(s));
        SignedIntegerSpatial { data: out }
    }

    /// Tries to convert this value from its current quantization to another quantization,
    /// returning an error if any axis value does not fit.
    pub fn try_to_quantization<ToQuant: QuantizedSignedIntegerTrait>(
        self,
    ) -> Result<SignedIntegerSpatial<ToQuant, NUM_DIMS>, FeagiDataValuesSpatialError> {
        let mut out = [ToQuant::QUANT_ZERO; NUM_DIMS];
        for (o, &s) in out.iter_mut().zip(self.data.iter()) {
            *o = s.try_to_quantization().map_err(|e| e.into())?;
        }
        Ok(SignedIntegerSpatial { data: out })
    }

    /// Converts this value from its current quantization to another quantization, clamping each
    /// axis value to fit.
    pub fn to_quantization_clamped<ToQuant: QuantizedSignedIntegerTrait>(self) -> SignedIntegerSpatial<ToQuant, NUM_DIMS> {
        let mut out = [ToQuant::QUANT_ZERO; NUM_DIMS];
        out.iter_mut().zip(self.data.iter()).for_each(|(o, &s)| *o = s.to_quantization_clamped());
        SignedIntegerSpatial { data: out }
    }

    /// Clamps each axis value for another quantization, but does not change the quantization itself.
    pub fn clamp_for_quantization<ClampFor: QuantizedSignedIntegerTrait>(self) -> Self {
        let mut data = self.data;
        data.iter_mut().for_each(|q| *q = q.clamp_for_quantization::<ClampFor>());
        Self { data }
    }

    /// Clamps each axis value for a runtime-provided quantization level, but does not change the
    /// quantization itself.
    pub fn clamp_for_quantization_level_runtime(self, level: SignedIntegerQuantizationLevel) -> Self {
        let mut data = self.data;
        data.iter_mut().for_each(|q| *q = q.clamp_for_quantization_level_runtime(level));
        Self { data }
    }

    /// Output to a [`SignedIntegerSpatialEnum`] to abstract away quantization.
    pub fn to_enum(self) -> SignedIntegerSpatialEnum<NUM_DIMS> {
        match Q::LEVEL {
            SignedIntegerQuantizationLevel::I8 => SignedIntegerSpatialEnum::I8(self.to_quantization_unchecked()),
            SignedIntegerQuantizationLevel::I16 => SignedIntegerSpatialEnum::I16(self.to_quantization_unchecked()),
            SignedIntegerQuantizationLevel::I32 => SignedIntegerSpatialEnum::I32(self.to_quantization_unchecked()),
            SignedIntegerQuantizationLevel::I64 => SignedIntegerSpatialEnum::I64(self.to_quantization_unchecked()),
        }
    }

    /// Get as a fixed-size array
    pub fn as_data_slice(&self) -> &[Q; NUM_DIMS] {
        &self.data
    }

    /// Get as a mutable fixed-size array
    pub fn as_data_slice_mut(&mut self) -> &mut [Q; NUM_DIMS] {
        &mut self.data
    }

    /// Get as a flat slice view of axis values
    pub fn as_slice(&self) -> &[Q] {
        self.data.as_slice()
    }

    /// Get as a mutable flat slice view of axis values
    pub fn as_slice_mut(&mut self) -> &mut [Q] {
        self.data.as_mut_slice()
    }

    /// Returns spatial data with all elements zero
    pub fn new_zero() -> Self {
        Self::QUANT_ZEROS
    }
}

