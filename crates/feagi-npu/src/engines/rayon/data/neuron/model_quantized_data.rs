impl<FIQ: FeagiIndexQuantization> NeuronModelData<FIQ> {

    pub fn allocate_for_new_area<NMQ: NeuronModelQuantization, NM: NeuronModel<FIQ, NMQ>>(&mut self, number_neurons: FIQ::NeuronIndexQuant) -> (&mut NM::CorticalData, &mut NM::NeuronData){
        match NM::NEURON_MODEL_AND_QUANTIZATION {
            NeuronModelTypeAndQuantizationNested::FeagiAdvanced(quant) => {
                match quant {
                    FeagiAdvancedModelQuantizationLevel::Standard => {
                        // some functions may need to be added
                        // append to end of vector, return mut reference to it
                        let cortical_ref: &mut NM::CorticalData  = self.feagi_advanced.quantization_standard.cortical_data.append_single_mut(NM::CorticalData::default());
                        //self.feagi_advanced.quantization_standard.psp_uniformity.extend(CorticalModelIndex::QUANT_ONE, 0.0);
                        // TODO PSP uniformity
                        // append to end of vector, return mut slice to it
                        let neuron_slice: &mut [NM::NeuronData] = self.feagi_advanced.quantization_standard.neuron_data.extend_mut(NeuronModelIndex::from(number_neurons), NM::NeuronData::default());
                        (cortical_ref, neuron_slice)
                    }
                }
            }
        }
    }

}

impl<FIQ: FeagiIndexQuantization> Default for NeuronModelData<FIQ> {
    fn default() -> Self {
        Self {
            feagi_advanced: ModelFeagiAdvanced::default()
        }
    }
}




#[doc(hidden)]
mod feagi_advanced_model {
    use feagi_data::quantization_levels::feagi_index_quantization::FeagiIndexQuantization;
    use feagi_models::neuron::models::feagi_advanced::{FeagiAdvancedModelCorticalData, FeagiAdvancedModelNeuronData, FeagiAdvancedModelStandardQuant};
    use feagi_models::wrapped_index_collections::{CorticalModelIndexedVector, NeuronModelIndexedVector};

    #[doc(hidden)]
    pub struct ModelFeagiAdvanced<FIQ: FeagiIndexQuantization> {
        pub quantization_standard: QuantizationStandard<FIQ>
    }

    impl<FIQ: FeagiIndexQuantization> Default for ModelFeagiAdvanced<FIQ> {
        fn default() -> Self {
            Self {
                quantization_standard: Default::default()
            }
        }
    }


    #[doc(hidden)]
    pub struct QuantizationStandard<FIQ: FeagiIndexQuantization> {
        pub cortical_data: CorticalModelIndexedVector
        <
            FIQ::CorticalAreaIndexCountQuant,
            FeagiAdvancedModelCorticalData<FeagiAdvancedModelStandardQuant>
        >,
        pub psp_uniformity: NeuronModelIndexedVector
        <
            FIQ::NeuronIndexQuant,
            FeagiAdvancedModelNeuronData<FeagiAdvancedModelStandardQuant>,
        >,
        pub neuron_data: NeuronModelIndexedVector
        <
            FIQ::NeuronIndexQuant,
            FeagiAdvancedModelNeuronData<FeagiAdvancedModelStandardQuant>,
        >,
    }

    quant_default_with_neurons!(QuantizationStandard);



}

