macro_rules! quant_default_with_neurons {
    ($struct_name:ident) => {
    impl<FIQ: FeagiIndexQuantization> Default for $struct_name<FIQ> {
        fn default() -> Self {
            Self {
                cortical_data: CorticalModelIndexedVector::new_empty(),
                psp_uniformity: NeuronModelIndexedVector::new_empty(),
                neuron_data: NeuronModelIndexedVector::new_empty(),
            }
        }
    }
    };
}

